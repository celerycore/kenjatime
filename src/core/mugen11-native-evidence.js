/**
 * Native-oracle comparison gate for the TargetState/ChangeAnim2/SelfState
 * milestone. A trace claiming to be from MUGEN is not proof of provenance;
 * this verifier only enforces metadata, scenario alignment and exact values.
 * It never launches a proprietary executable and cannot certify the engine.
 */
import {compareLegacyTraces} from "./legacy-compatibility.js";

export const MUGEN11_ORACLE_ENGINE="Elecbyte M.U.G.E.N";
export const MUGEN11_ORACLE_RELEASE="1.1 Beta 1 P1";
const sha256=value=>typeof value==="string"&&/^[a-f0-9]{64}$/i.test(value);
const requireNonempty=(value,name)=>{
  if(typeof value!=="string" || !value.trim())throw Error(name+" is required.");
  return value.trim();
};

export function validateMugen11NativeOracleEvidence(reference,candidate) {
  if(!reference || typeof reference!=="object")throw Error("Native reference object is required.");
  if(!candidate || typeof candidate!=="object" || candidate.source!=="kenjatime-synthetic")
    throw Error("Candidate must be generated by Kenjatime's synthetic state probe.");
  if(reference.source!=="native-mugen11")
    throw Error("Reference must identify an independently captured native-mugen11 source.");
  const provenance=reference.provenance;
  if(!provenance || provenance.engine!==MUGEN11_ORACLE_ENGINE ||
      provenance.release!==MUGEN11_ORACLE_RELEASE)
    throw Error("Elecbyte M.U.G.E.N 1.1 Beta 1 P1 provenance is required.");
  for(const key of ["executableSha256","attackerAssetsSha256","victimAssetsSha256"])
    if(!sha256(provenance[key]))throw Error("Native provenance "+key+" requires a SHA-256 checksum.");
  requireNonempty(provenance.captureMethod,"Native capture method");
  requireNonempty(provenance.stage,"Native stage");
  requireNonempty(provenance.inputSequence,"Native input sequence");
  if(reference.scenario!==candidate.scenario)
    throw Error("Native and Kenjatime scenario IDs differ.");
  if(!Array.isArray(reference.ticks)||reference.ticks.length===0)
    throw Error("Reference requires nonempty independently captured tick observations.");
  if(!Array.isArray(candidate.ticks)||candidate.ticks.length===0)
    throw Error("Kenjatime candidate requires nonempty tick observations.");
  const compared=compareLegacyTraces({ticks:reference.ticks},{ticks:candidate.ticks});
  return {
    ...compared,scenario:candidate.scenario,
    nativeReferenceClaimed:true,
    nativeReferenceAuthenticated:false, // Metadata alone cannot prove authenticity.
    fullMugen11Certified:false,          // One trace is not full engine parity.
    referenceEngine:provenance.engine+" "+provenance.release,
  };
}
